const $ = (sel, ctx = document) => ctx.querySelector(sel);
const $$ = (sel, ctx = document) => [...ctx.querySelectorAll(sel)];

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/*
 * Data access.
 * - With the Flask backend running, data comes from the /api/* endpoints.
 * - On static hosting (GitHub Pages) there is no backend, so the same
 *   endpoints are answered from data/db.json (generated by
 *   ingestion/export_static.py from data/istqb.db).
 */
let dataMode = null; // null (unknown) | 'api' | 'static'
let staticDb = null;

async function loadStaticDb() {
  if (!staticDb) {
    const res = await fetch('data/db.json');
    if (!res.ok) throw new Error(`Static data not found (data/db.json): ${res.status}`);
    staticDb = await res.json();
  }
  return staticDb;
}

function queryStaticDb(db, path) {
  const url    = new URL(path, 'http://static.local');
  const route  = url.pathname;
  const params = url.searchParams;

  if (route === '/api/chapters') {
    return db.chapters.map(({ id, number, title }) => ({ id, number, title }));
  }

  const chapterMatch = route.match(/^\/api\/chapters\/(\d+)$/);
  if (chapterMatch) {
    const ch = db.chapters.find(c => c.id === Number(chapterMatch[1]));
    if (!ch) throw new Error(`Chapter not found: ${chapterMatch[1]}`);
    const glossary = (db.glossary || [])
      .filter(g => g.chapter_id === ch.id)
      .sort((a, b) => a.term.localeCompare(b.term))
      .map(({ id, term, definition }) => ({ id, term, definition }));
    const math_types = (db.math_types || [])
      .filter(m => m.chapter_id === ch.id)
      .sort((a, b) => a.id - b.id);
    return { ...ch, glossary, math_types };
  }

  if (route === '/api/math-types') {
    const chapter = params.get('chapter');
    const mts = db.math_types || [];
    return chapter ? mts.filter(m => m.chapter_id === Number(chapter)) : mts;
  }

  if (route === '/api/questions') {
    const chapter = params.get('chapter');
    return chapter ? db.questions.filter(q => q.chapter_id === Number(chapter)) : db.questions;
  }

  if (route === '/api/theory-cards') {
    const chapter = params.get('chapter');
    const kLevel  = params.get('k_level');
    return db.theory_cards.filter(c =>
      (!chapter || c.chapter_id === Number(chapter)) &&
      (!kLevel  || c.k_level === kLevel.toUpperCase())
    );
  }

  throw new Error(`Unknown endpoint: ${path}`);
}

async function api(path) {
  if (dataMode !== 'static') {
    try {
      const res = await fetch(path);
      const isJson = (res.headers.get('content-type') || '').includes('application/json');
      if (res.ok && isJson) {
        dataMode = 'api';
        return res.json();
      }
      if (dataMode === 'api') throw new Error(`API error ${res.status}: ${path}`);
    } catch (err) {
      if (dataMode === 'api') throw err;
    }
    // No backend answered — fall back to the bundled static data.
    dataMode = 'static';
  }
  return queryStaticDb(await loadStaticDb(), path);
}

