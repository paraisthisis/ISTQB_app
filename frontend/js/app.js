function showView(name) {
  window.state.view = name;
  $$('.view').forEach(el => el.classList.remove('active'));
  $$('.nav-links button').forEach(btn => btn.classList.remove('active'));

  const viewEl = $(`#view-${name}`);
  const navBtn  = $(`[data-view="${name}"]`);
  if (viewEl) viewEl.classList.add('active');
  if (navBtn) navBtn.classList.add('active');

  if (name === 'study')    initStudy();
  if (name === 'practice') initPractice();
  if (name === 'theory')   initTheory();
  if (name === 'formulas') initFormulas();
  if (name === 'mock')     initMock();
}

